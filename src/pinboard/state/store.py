"""The interface every state store implements: MemoryStore (tests, local) and PostgresStore (production) must behave identically."""
from __future__ import annotations

from datetime import datetime
from typing import Protocol
from pinboard.state.records import (ApprovalRecord, ArtifactRecord, McpServerRecord, RunRecord, ScheduleRecord, ScheduleRunRecord, SessionRecord, SpareRecord)


class StateStore(Protocol):
    def setup(self) -> None: ...
    def create_run(self, run: RunRecord) -> None: ...
    def get_run(self, run_id: str) -> RunRecord | None: ...
    def update_run(self, run_id: str, **fields) -> RunRecord: ...
    def claim_run(self, run_id: str, from_status: str, to_status: str, now: datetime) -> bool: ...
    def active_run_for_thread(self, thread_id: str) -> RunRecord | None: ...
    def create_approval(self, approval: ApprovalRecord) -> None: ...
    def get_approval(self, approval_id: str) -> ApprovalRecord | None: ...
    def list_approvals(self, user_id: str, status: str | None = None, limit: int = 50) -> list[ApprovalRecord]: ...
    def decide_approval(self, approval_id: str, status: str, decision: dict, decided_by: str, now: datetime) -> ApprovalRecord | None: ...
    def expire_approvals(self, now: datetime) -> list[ApprovalRecord]: ...
    def add_audit(self, user_id: str, run_id: str | None, event: str, detail: dict, now: datetime | None = None) -> None: ...
    def list_audit(self, run_id: str | None = None, limit: int = 200) -> list[dict]: ...
    # sessions
    def create_session(self, session: SessionRecord) -> None: ...
    def get_session(self, session_id: str) -> SessionRecord | None: ...
    def update_session(self, session_id: str, **fields) -> SessionRecord: ...
    def list_sessions(self, user_id: str, limit: int = 50, include_archived: bool = False) -> list[SessionRecord]: ...
    def idle_sessions_with_sandbox(self, before: datetime) -> list[SessionRecord]: ...
    # turn leases (fencing): only the holder of the current lease may write events for a turn
    def acquire_lease(self, run_id: str, lease_id: str, now: datetime, ttl_seconds: float) -> bool: ...
    def renew_lease(self, run_id: str, lease_id: str, now: datetime, ttl_seconds: float) -> bool: ...
    def release_lease(self, run_id: str, lease_id: str) -> bool: ...
    def stale_runs(self, now: datetime, grace_seconds: float = 120) -> list[RunRecord]: ...
    def mark_interrupted(self, run_id: str, now: datetime, grace_seconds: float = 120) -> bool: ...
    def request_cancel(self, run_id: str) -> RunRecord: ...
    # event log
    def append_event(self, run_id: str, lease_id: str | None, type: str, payload: dict, now: datetime | None = None) -> int | None: ...
    def list_events(self, run_id: str, after_seq: int = 0, limit: int = 500) -> list[dict]: ...
    def delete_token_events(self, run_id: str, message_id: str | None) -> int: ...
    def last_event_of_type(self, run_id: str, type: str) -> dict | None: ...
    def list_session_runs(self, session_id: str, limit: int = 50) -> list[RunRecord]: ...
    # spare sandboxes (the warm pool)
    def begin_spare(self, spare_id: str, now: datetime, stale_before: datetime, since: datetime, max_since: int) -> bool: ...
    def finish_spare(self, spare_id: str, name: str, now: datetime, expires_at: datetime) -> bool: ...
    def delete_spare(self, spare_id: str) -> None: ...
    def current_spare(self, stale_before: datetime) -> SpareRecord | None: ...
    def claim_spare(self, session_id: str, now: datetime, min_remaining_seconds: float) -> SpareRecord | None: ...
    def spares_to_sweep(self, now: datetime, unclaimed_before: datetime, stale_before: datetime) -> list[SpareRecord]: ...
    def purge_claimed_spares(self, before: datetime) -> int: ...
    # artifacts
    def create_artifact(self, artifact: ArtifactRecord) -> None: ...
    def get_artifact(self, artifact_id: str) -> ArtifactRecord | None: ...
    def list_artifacts(self, user_id: str, session_id: str | None = None, limit: int = 50) -> list[ArtifactRecord]: ...
    def latest_artifact(self, user_id: str, session_id: str, path: str) -> ArtifactRecord | None: ...
    # bring-your-own MCP servers (unique per user and name)
    def put_mcp_server(self, server: McpServerRecord) -> McpServerRecord: ...
    def get_mcp_server(self, user_id: str, name: str) -> McpServerRecord | None: ...
    def list_mcp_servers(self, user_id: str) -> list[McpServerRecord]: ...
    def update_mcp_server(self, user_id: str, name: str, **fields) -> McpServerRecord | None: ...
    def delete_mcp_server(self, user_id: str, name: str) -> bool: ...
    # scheduled tasks
    def create_schedule(self, schedule: ScheduleRecord) -> None: ...
    def get_schedule(self, schedule_id: str) -> ScheduleRecord | None: ...
    def list_schedules(self, user_id: str) -> list[ScheduleRecord]: ...
    def update_schedule(self, schedule_id: str, **fields) -> ScheduleRecord | None: ...
    def delete_schedule(self, schedule_id: str) -> bool: ...
    def due_schedules(self, now: datetime, limit: int = 50) -> list[ScheduleRecord]: ...
    def claim_schedule(self, schedule_id: str, expected_next_run: datetime, new_next_run: datetime | None, now: datetime) -> bool: ...
    def add_schedule_run(self, run: ScheduleRunRecord) -> None: ...
    def update_schedule_run(self, run_id: str, **fields) -> None: ...
    def list_schedule_runs(self, schedule_id: str, limit: int = 20) -> list[ScheduleRunRecord]: ...
    def count_schedule_runs_since(self, user_id: str, since: datetime) -> int: ...
